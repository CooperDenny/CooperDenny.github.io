"""Project pages. Every page is a ProjectPage; how it's produced differs per subclass."""

from __future__ import annotations

from abc import ABC, abstractmethod
from pathlib import Path
from typing import Optional

from .extensions import ReportExtension
from .images import webp_size
from .model import PageCopy
from .render import REPORT_CSS, SITE_CSS, TOKENS_CSS, Renderer
from .transforms import (
    FoldCodeChunks,
    FoldLongOutputs,
    MarkedBlock,
    Pipeline,
    RemoveLegacyChrome,
    RemoveLegacyHeadAssets,
    SetBodyClass,
    SetTitle,
    UpsertBlock,
    insert_after,
    insert_before,
    replace_pattern,
)

GENERATED_NOTE = "<!-- Generated by scripts/build-project-pages.py — edit the copy there, then re-run it. -->"


class ProjectPage(ABC):
    """A /projects/<slug>/index.html file. Subclasses decide how its HTML is produced."""

    def __init__(self, copy: PageCopy, renderer: Renderer, projects_dir: Path):
        self.copy, self.r = copy, renderer
        self.path = projects_dir / copy.slug / "index.html"

    @property
    def slug(self) -> str:
        """The page's URL slug."""
        return self.copy.slug

    def current(self) -> Optional[str]:
        """The HTML on disk now, or None if the file doesn't exist yet."""
        return self.path.read_text(encoding="utf-8") if self.path.exists() else None

    @abstractmethod
    def render(self, current: Optional[str]) -> str:
        """The page's HTML, given what's on disk now (None if nothing)."""

    def build(self, write: bool = True) -> bool:
        """Render; write if `write`. Returns True if the output differs from what's on disk."""
        before = self.current()
        after = self.render(before)
        if write and after != before:
            self.path.parent.mkdir(parents=True, exist_ok=True)  # a new hand page needs its folder
            self.path.write_text(after, encoding="utf-8")
        return after != before


class HandPage(ProjectPage):
    """Generated in full from its copy."""

    def render(self, current: Optional[str]) -> str:
        c, r = self.copy, self.r
        return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{r.page_title(c)}</title>
{r.head_meta(c)}
{r.analytics()}
{r.fonts()}
{r.stylesheets(TOKENS_CSS, SITE_CSS)}
{GENERATED_NOTE}
</head>
<body class="cd-page">
{MarkedBlock("nav").wrap(r.nav())}
<main id="cd-main">
{r.hero(c)}
<div class="cd-wrap">
{r.summary(c)}
<article class="cd-article">
{r.article(c, self._image_size)}
</article>
</div>
</main>
{MarkedBlock("next").wrap(r.next_project(c.slug))}
</body>
</html>
"""


    def _image_size(self, relative: str) -> Optional[tuple[int, int]]:
        """(width, height) of a WebP next to this page, or None if it isn't there."""
        return webp_size(self.path.parent / relative)


class ReportPage(ProjectPage):
    """knitr output, enhanced in place: the body is never touched, only wrapped in shared chrome."""

    BODY_CLASS = "cd-page cd-report"

    def __init__(self, copy: PageCopy, renderer: Renderer, projects_dir: Path, extension: Optional[ReportExtension] = None):
        super().__init__(copy, renderer, projects_dir)
        self.extension = extension or ReportExtension()

    def render(self, current: Optional[str]) -> str:
        if current is None:
            raise FileNotFoundError(f"{self.path}: knit the report from its .Rmd first")
        copy = self.extension.enrich(self.copy, current)
        return self._pipeline(copy).run(current)

    def _pipeline(self, copy: PageCopy) -> Pipeline:
        r = self.r
        head, nav, header, next_ = (MarkedBlock(n) for n in ("head", "nav", "header", "next"))
        body_tag = f'<body class="{self.BODY_CLASS}">'
        return Pipeline(
            [
                *self.extension.transforms(),
                SetTitle(r.page_title(copy)),
                RemoveLegacyHeadAssets(),
                UpsertBlock(head, head.wrap(self._head(copy)), insert_before("</head>")),
                SetBodyClass(self.BODY_CLASS),
                RemoveLegacyChrome(),
                UpsertBlock(nav, nav.wrap(r.nav()), insert_after(body_tag)),
                UpsertBlock(header, header.wrap(self._header(copy)), replace_pattern(r'<div id="header">.*?</div>', "pandoc's #header block")),
                FoldCodeChunks(),
                FoldLongOutputs(),
                UpsertBlock(next_, next_.wrap(r.next_project(copy.slug)), insert_before("</body>")),
            ]
        )

    def _head(self, copy: PageCopy) -> str:
        r = self.r
        return "\n".join(
            [
                '<meta name="viewport" content="width=device-width, initial-scale=1">',
                r.head_meta(copy),
                r.fonts(),
                r.stylesheets(TOKENS_CSS, SITE_CSS, REPORT_CSS),
            ]
        )

    def _header(self, copy: PageCopy) -> str:
        return f'<div id="cd-main">\n{self.r.hero(copy)}\n{self.r.summary(copy)}\n</div>'
